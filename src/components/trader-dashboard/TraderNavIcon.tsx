/** Rendered on the Figma 24px slot; each glyph keeps its exported viewBox and size. */
export function TraderNavIcon({ name, active }: { name: TraderNavIconName; active: boolean }) {
  const gradientId = useId();
  const icon: { box: number; kind: "fill" | "stroke"; evenOdd?: boolean; strokeWidth?: number; paths: readonly string[] } = ICONS[name];
  const paint = active ? `url(#${gradientId})` : "white";
  // Settings' export is 18×20 inside its 20px box.
  const w = name === "settings" ? 18 : icon.box;

  return (
    <svg aria-hidden width={w} height={icon.box} viewBox={`0 0 ${w} ${icon.box}`} fill="none">
      <defs>
        <linearGradient id={gradientId} x1="0" y1="0" x2={w} y2={icon.box} gradientUnits="userSpaceOnUse">
          <stop stopColor="white" />
          <stop offset="1" stopColor="#99804A" />
        </linearGradient>
      </defs>
      {icon.paths.map((d) =>
        icon.kind === "fill" ? (
          <path
            key={d}
            d={d}
            fill={paint}
            fillOpacity={active ? 1 : 0.5}
            fillRule={icon.evenOdd ? "evenodd" : undefined}
            clipRule={icon.evenOdd ? "evenodd" : undefined}
          />
        ) : (
          <path
            key={d}
            d={d}
            stroke={paint}
            strokeOpacity={active ? 1 : 0.5}
            strokeWidth={icon.strokeWidth ?? 1.5}
            strokeLinecap="round"
            strokeLinejoin="round"
          />
        ),
      )}
    </svg>
  );
}
